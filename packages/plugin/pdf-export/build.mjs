/**
 * Builds and verifies the browser half of the PDF export plugin.
 *
 * `bun packages/plugin/pdf-export/build.mjs`
 *
 * The bundle is executed against a fake client, because a bundle that evaluates
 * but registers no entry fails only in the browser.
 */

import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
const DIR = join(ROOT, 'packages', 'plugin', 'pdf-export')
const ID = '@prometheus-harness/pdf-export'
const TARGET = join(DIR, 'lib', 'client.js')

/**
 * Wrap the CommonJS body in the loader envelope.
 *
 * @param body - built CommonJS body
 * @returns the complete module file
 */
function wrap(body) {
  const indented = body
    .split('\n')
    .map((line) => (line.length > 0 ? `\t\t${line}` : line))
    .join('\n')
  return `/**
 * Browser half. GENERATED by \`packages/plugin/pdf-export/build.mjs\`.
 * Do not edit by hand: the source is \`packages/plugin/pdf-export/src/client.tsx\`.
 */
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(ID)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
${indented}
\t\treturn module.exports;
\t}
});
`
}

/** Execute the bundle against a client that only records slot registrations. */
function verify(text) {
  const failures = []
  const findings = []

  // Build-time externals drift: the platform seed table holds only the seven
  // words in `packages/client/web/src/platform.ts` — `react/jsx-dev-runtime`
  // is NOT one of them. A bundle that asks for it misses the module table in
  // the browser and silently fails activation (measured: `web boot: 1 entry
  // did not activate`). The gate reads the built text, before the factory
  // runs, so the failure names the drift instead of a require miss.
  if (text.includes('react/jsx-dev-runtime')) {
    failures.push(
      'bundle requires react/jsx-dev-runtime — the platform seed table has no dev runtime; '
        + 'build with jsx: { runtime: "automatic", development: false }',
    )
  }

  const registrations = []
  const disposers = []

  const slots = {
    inject: (name, factory) => {
      const dispose = factory()
      if (typeof dispose === 'function') disposers.push(dispose)
      return dispose
    },
    register: (spec, component) => {
      registrations.push({ spec, component })
      return () => {}
    },
  }
  const ctx = {
    slots,
    effect: (factory) => {
      const dispose = factory()
      if (typeof dispose === 'function') disposers.push(dispose)
      return dispose
    },
    inject: (services, factory) => {
      const dispose = factory({ effect: () => {} })
      if (typeof dispose === 'function') disposers.push(dispose)
      return dispose
    },
  }

  const window = { __ModuleLoader__: { load: ({ id, factory }) => {
    if (id !== ID) failures.push(`bundle id ${String(id)} does not match ${ID}.`)
    const exports = factory((name) => {
      // Only seed words may be satisfied. The dev runtime is deliberately
      // absent: a build that asks for it must go red here, not green in the
      // browser (docs/status/arbeitsweise.md, rule 41).
      if (name === 'react' || name === 'react/jsx-runtime') return {}
      throw new Error(`unexpected require ${name}`)
    })
    if (typeof exports.apply !== 'function') failures.push('bundle does not export apply().')
    else exports.apply(ctx)
  } } }
  try {
    // eslint-disable-next-line no-new-func
    new Function('window', text)(window)
  } catch (error) {
    failures.push(`bundle threw: ${error instanceof Error ? error.message : String(error)}`)
  }

  const header = registrations.find((entry) => entry.spec.name === 'conversation.session.header.actions' && entry.spec.id === 'pdf-export')
  const protocol = registrations.find((entry) => entry.spec.name === 'conversation.session.header.actions' && entry.spec.id === 'pdf-export-protocol')
  const message = registrations.find((entry) => entry.spec.name === 'conversation.chat.assistant-actions')
  if (header === undefined) failures.push('session header entry is missing.')
  if (protocol === undefined) failures.push('session header protocol entry is missing.')
  if (message?.spec.id !== 'pdf-export') failures.push('assistant action entry is missing.')
  if (registrations.length !== 3) failures.push(`registered ${registrations.length} entries instead of three.`)
  if (header !== undefined) findings.push(`header entry: ${header.spec.id}`)
  if (protocol !== undefined) findings.push(`header entry: ${protocol.spec.id}`)
  if (message !== undefined) findings.push(`message entry: ${message.spec.id}`)
  for (const dispose of disposers) dispose()
  return { failures, findings }
}

/**
 * Module requests the shell's frozen platform table answers.
 *
 * A request outside this list cannot be resolved in the browser: the module
 * table has no factory for it, activation fails, and the Web boot audit blocks
 * the whole page. That is exactly what happened with `react/jsx-dev-runtime`:
 * a development JSX build requested a runtime the shell never seeds.
 */
const PLATFORM_MODULE_ALLOWLIST = new Set(['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'])

/** Every `require("…")` the bundle performs. */
function bundleRequires(text) {
  return [...new Set([...text.matchAll(/require\("([^"]+)"\)/gu)].map((match) => match[1]))]
}

const result = await Bun.build({
  entrypoints: [join(DIR, 'src', 'client.tsx')],
  format: 'cjs',
  target: 'browser',
  // Production JSX: the development runtime is not part of the shell's module
  // table, so a dev build cannot load at all.
  jsx: { runtime: 'automatic', importSource: 'react', development: false },
  define: { 'process.env.NODE_ENV': '"production"' },
  external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'],
})
if (!result.success) {
  for (const log of result.logs) console.error(log)
  process.exit(1)
}

const body = await result.outputs[0].text()
const requires = bundleRequires(body)
const unresolvable = requires.filter((request) => !PLATFORM_MODULE_ALLOWLIST.has(request))
if (unresolvable.length > 0 || body.includes('jsx-dev-runtime')) {
  console.error('\nRefusing to write an unbootable bundle:')
  for (const request of unresolvable) console.error(`  - require("${request}") is not in the platform module table`)
  if (body.includes('jsx-dev-runtime')) console.error('  - bundle references react/jsx-dev-runtime (development JSX build)')
  process.exit(1)
}
console.log(`Module requests: ${requires.length === 0 ? 'none' : requires.join(', ')}`)

const built = wrap(body)
mkdirSync(dirname(TARGET), { recursive: true })
writeFileSync(TARGET, built, 'utf8')
console.log(`Built: ${TARGET} (${String(Buffer.byteLength(built))} B)`)

const { failures, findings } = verify(built)
console.log('\n== Bundle check ==')
for (const finding of findings) console.log(`  ${finding}`)
if (failures.length > 0) {
  console.error('\nFailed:')
  for (const failure of failures) console.error(`  - ${failure}`)
  process.exit(1)
}
console.log('  Form and registration: ok')
