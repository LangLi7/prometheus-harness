/**
 * Builds and verifies the browser half of the rich UI plugin.
 *
 * `bun packages/plugin/rich-ui/build.mjs`
 *
 * The Host loads built bundles, so this script wraps the Bun build in the
 * `__ModuleLoader__` envelope and then *executes* the result against a fake client:
 * a bundle that evaluates cleanly but registers nothing would otherwise only fail
 * in the browser.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
const DIR = join(ROOT, 'packages', 'plugin', 'rich-ui')
const ID = '@prometheus-harness/rich-ui'
const TARGET = join(DIR, 'lib', 'client.js')

/**
 * Wrap the CommonJS body in the loader envelope.
 *
 * @param body - built CommonJS body
 * @returns the complete module file
 */
function wrap(body) {
  const indented = body
    .split('\n')
    .map((line) => (line.length > 0 ? `\t\t${line}` : line))
    .join('\n')
  return `/**
 * Browser half. GENERATED by \`packages/plugin/rich-ui/build.mjs\`.
 * Do not edit by hand: the source is \`packages/plugin/rich-ui/src/client.tsx\`.
 */
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(ID)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
${indented}
\t\treturn module.exports;
\t}
});
`
}

const SAMPLE = {
  kind: 'chart',
  title: 'Umsatzentwicklung',
  subtitle: 'Demonstrationsdaten',
  footer: 'Beispieldaten',
  chart: {
    type: 'line',
    unit: '€',
    labels: ['Jan', 'Feb', 'Mär', 'Apr'],
    series: [{ key: 'revenue', label: 'Umsatz', values: [120, 180, 150, 240] }],
  },
}

/**
 * Execute the built bundle and interrogate the plugin it produces.
 *
 * @param text - the bundle file content
 * @returns findings and failures
 */
function verify(text) {
  const failures = []
  const findings = []
  let registered

  const windowStub = { __ModuleLoader__: { load: (definition) => (registered = definition) } }
  try {
    new Function('window', text)(windowStub)
  } catch (error) {
    return { failures: [`Not evaluable: ${error instanceof Error ? error.message : String(error)}`], findings }
  }
  if (registered === undefined) return { failures: ['No __ModuleLoader__.load in the bundle.'], findings }
  if (registered.id !== ID) failures.push(`Bundle id is ${JSON.stringify(registered.id)} instead of ${JSON.stringify(ID)}.`)
  findings.push(`id: ${String(registered.id)}`)

  const requested = []
  const jsx = () => null
  const reactStub = {
    createElement: () => null,
    Fragment: null,
    useState: (value) => [value, () => undefined],
  }
  let plugin
  try {
    plugin = registered.factory((name) => {
      requested.push(name)
      if (name === 'react/jsx-runtime' || name === 'react/jsx-dev-runtime') {
        return { jsx, jsxs: jsx, Fragment: null }
      }
      return reactStub
    })
  } catch (error) {
    return { failures: [...failures, `Factory threw: ${error instanceof Error ? error.message : String(error)}`], findings }
  }
  const unexpected = requested.filter((name) => name !== 'react' && name !== 'react/jsx-runtime')
  if (unexpected.length > 0) failures.push(`Unexpected module requests: ${unexpected.join(', ')}.`)

  if (plugin === null || typeof plugin !== 'object') return { failures: [...failures, 'Factory did not return a plugin object.'], findings }
  if (typeof plugin.apply !== 'function') failures.push('apply is missing.')
  if (!Array.isArray(plugin.inject)) failures.push('inject is missing.')
  else if (!plugin.inject.includes('slots') || !plugin.inject.includes('uiConversation')) {
    failures.push(`inject is ${JSON.stringify(plugin.inject)}; it must name slots and uiConversation.`)
  }
  if (failures.length > 0) return { failures, findings }
  findings.push(`inject: ${JSON.stringify(plugin.inject)}`)

  const disposers = []
  const slots = []
  let definition
  const ctx = {
    effect: (fn) => {
      const dispose = fn()
      if (typeof dispose === 'function') disposers.push(dispose)
    },
    slots: {
      inject: (name, callback) => {
        callback()
      },
      register: (spec, component) => {
        slots.push({ spec, component })
        return () => undefined
      },
    },
    uiConversation: {
      events: {
        register: (contribution) => {
          definition = contribution
          return () => undefined
        },
      },
    },
  }

  const previousDocument = globalThis.document
  const styles = []
  globalThis.document = {
    createElement: () => ({ dataset: {}, textContent: '', remove: () => undefined }),
    head: { append: (style) => styles.push(style) },
  }
  try {
    plugin.apply(ctx)
  } catch (error) {
    globalThis.document = previousDocument
    return { failures: [...failures, `apply threw: ${error instanceof Error ? error.message : String(error)}`], findings }
  } finally {
    globalThis.document = previousDocument
  }

  if (styles.length !== 1) failures.push(`apply installed ${String(styles.length)} style elements instead of one.`)
  if (typeof styles[0]?.textContent !== 'string' || !styles[0].textContent.includes('--dsw-alias-')) {
    failures.push('The injected stylesheet does not use theme tokens (--dsw-alias-*).')
  }

  if (definition === undefined) failures.push('No Conversation Definition was registered.')
  else {
    if (definition.kind !== 'rich-ui') failures.push(`Definition kind is ${JSON.stringify(definition.kind)} instead of "rich-ui".`)
    if (definition.target !== 'chat') failures.push(`Definition target is ${JSON.stringify(definition.target)} instead of "chat".`)

    const call = {
      type: 'tool/call',
      seq: 42,
      data: { name: 'render_ui', callId: 'call-1', arguments: JSON.stringify(SAMPLE) },
    }
    const match = definition.match(call)
    if (match?.id !== 'call-1' || match.role !== 'start') failures.push('match did not accept the render_ui call.')
    if (definition.match({ ...call, data: { ...call.data, name: 'read' } }) !== null) failures.push('match accepted a foreign tool name.')

    const context = {
      key: 'rich-ui:call-1',
      kind: 'rich-ui',
      id: 'call-1',
      matches: [],
      start: { event: call, role: 'start', location: { kind: 'turn', turn: 1 } },
      state: undefined,
      current: new Map(),
    }
    let state
    try {
      state = definition.start(context, context.start)
    } catch (error) {
      failures.push(`start threw: ${error instanceof Error ? error.message : String(error)}`)
    }
    if (state !== undefined) {
      if (state.spec?.kind !== 'chart') failures.push('start did not normalize the chart.')
      else findings.push(`start: chart with ${String(state.spec.chart?.labels.length ?? 0)} labels`)
      const node = definition.buildViewNode({ ...context, state })
      if (node?.kind !== 'rich-ui' || node.target !== 'chat') failures.push('buildViewNode did not publish a chat node.')
      if (node?.anchorSeq !== 42) failures.push(`anchorSeq is ${String(node?.anchorSeq)} instead of 42.`)
      if (node?.visibility !== 'visible') failures.push('The card node must stay visible at the tool call.')
      if (node?.data?.spec?.chart?.type !== 'line') failures.push('The published node lost the chart description.')

      const broken = definition.start(
        { ...context, key: 'rich-ui:call-2', id: 'call-2', start: { ...context.start, event: { ...call, data: { ...call.data, arguments: '{"kind":' } } } },
        { ...context.start, event: { ...call, data: { ...call.data, arguments: '{"kind":' } } },
      )
      if (broken?.error === null || broken?.spec !== null) failures.push('Truncated arguments did not produce a readable error state.')
    }
  }

  const nodeView = slots.find((entry) => entry.spec.name === 'conversation.chat.node')
  const tail = slots.find((entry) => entry.spec.name === 'conversation.chat.turnTail')
  const toolRow = slots.find((entry) => entry.spec.name === 'tool.call.toolview')
  if (nodeView?.spec.key !== 'rich-ui') failures.push('The rich-ui process card renderer is missing.')
  if (tail?.spec.id !== 'rich-ui') failures.push('The rich-ui Turn-tail entry is missing.')
  if (toolRow?.spec.key !== 'render_ui') failures.push('The render_ui tool view is missing.')
  if (slots.length !== 3) failures.push(`apply registered ${String(slots.length)} slot entries instead of three.`)

  for (const dispose of disposers) {
    try {
      dispose()
    } catch (error) {
      failures.push(`A disposer threw: ${error instanceof Error ? error.message : String(error)}`)
    }
  }

  if (failures.length === 0) findings.push('Definition, all three slot entries, and the stylesheet are wired.')
  return { failures, findings }
}

const result = await Bun.build({
  entrypoints: [join(DIR, 'src', 'client.tsx')],
  target: 'browser',
  format: 'cjs',
  jsx: { runtime: 'automatic', importSource: 'react', development: false },
  minify: false,
  sourcemap: false,
  external: ['react', 'react/jsx-runtime', 'react/jsx-dev-runtime'],
})
if (!result.success) {
  console.error('Build failed:')
  for (const log of result.logs) console.error(`  ${String(log)}`)
  process.exit(1)
}
const output = result.outputs[0]
if (output === undefined) {
  console.error('Build produced no output.')
  process.exit(1)
}

const text = wrap(await output.text())
mkdirSync(dirname(TARGET), { recursive: true })
writeFileSync(TARGET, text, 'utf8')
console.log(`Built: ${TARGET} (${String(Buffer.byteLength(readFileSync(TARGET)))} B)`)

const { failures, findings } = verify(text)
console.log('')
console.log('== Bundle check ==')
for (const finding of findings) console.log(`  ${finding}`)
if (failures.length > 0) {
  console.error('')
  for (const failure of failures) console.error(`FAIL: ${failure}`)
  process.exit(1)
}
console.log('  Form and registration: ok')
